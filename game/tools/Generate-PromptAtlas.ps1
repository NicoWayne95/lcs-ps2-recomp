param([string]$Source = (Join-Path $PSScriptRoot '../src/lcs/prompt_assets'))
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$names = @(
 'keyboard_enter keyboard_escape keyboard_space keyboard_shift keyboard_f keyboard_w keyboard_s keyboard_a keyboard_d keyboard_tab keyboard_h keyboard_v keyboard_2 keyboard_y keyboard_x keyboard_z keyboard_q keyboard_e keyboard_c keyboard_arrows keyboard_arrow_up keyboard_arrow_down keyboard_arrow_left keyboard_arrow_right keyboard_arrows_horizontal keyboard_arrows_vertical mouse mouse_left mouse_right mouse_scroll mouse_scroll_up mouse_scroll_down mouse_move',
 'xbox_button_color_a xbox_button_color_b xbox_button_color_x xbox_button_color_y xbox_lb xbox_rb xbox_lt xbox_rt xbox_ls xbox_rs xbox_stick_l xbox_stick_r xbox_dpad xbox_dpad_up xbox_dpad_down xbox_dpad_left xbox_dpad_right xbox_dpad_vertical xbox_dpad_horizontal xbox_button_menu xbox_button_view',
 'playstation_button_color_cross playstation_button_color_circle playstation_button_color_square playstation_button_color_triangle playstation_trigger_l1 playstation_trigger_r1 playstation_trigger_l2 playstation_trigger_r2 playstation_button_l3 playstation_button_r3 playstation_stick_l playstation_stick_r playstation_dpad playstation_dpad_up playstation_dpad_down playstation_dpad_left playstation_dpad_right playstation_dpad_vertical playstation_dpad_horizontal playstation5_button_options playstation5_button_create playstation_button_cross playstation_button_circle playstation_button_square playstation_button_triangle playstation_button_color_cross_outline playstation_button_color_circle_outline playstation_button_color_square_outline playstation_button_color_triangle_outline playstation_button_l3_outline playstation_button_r3_outline playstation_trigger_l1_outline playstation_trigger_r1_outline playstation_trigger_l2_outline playstation_trigger_r2_outline playstation3_button_start_outline playstation3_button_select_outline playstation4_button_options_outline playstation4_button_share_outline'
)
$folders = @('keyboard-mouse','xbox-series','playstation-series')
$out = [Text.StringBuilder]::new()
[void]$out.AppendLine('// Generated by tools/Generate-PromptAtlas.ps1 from Kenney Input Prompts (CC0).')
[void]$out.AppendLine('enum Icon : unsigned { Original,')
$rows = [Collections.Generic.List[object]]::new()
for ($pack = 0; $pack -lt $folders.Length; $pack++) {
  foreach ($name in $names[$pack].Split(' ')) {
    if ($name -eq 'keyboard_two') { continue }
    $path = Join-Path (Join-Path $Source $folders[$pack]) ($name + '.png')
    $bmp = [Drawing.Bitmap]::new($path)
    $side = 64
    $scale = [Math]::Min(1.0, 60.0 / [Math]::Max($bmp.Width,$bmp.Height))
    if ($scale -lt 1.0) {
      $small = [Drawing.Bitmap]::new([int]($bmp.Width*$scale),[int]($bmp.Height*$scale))
      $graphics = [Drawing.Graphics]::FromImage($small)
      $graphics.InterpolationMode = [Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
      $graphics.DrawImage($bmp,0,0,$small.Width,$small.Height)
      $graphics.Dispose()
      $bmp.Dispose()
      $bmp = $small
    }
    $pixels = [Collections.Generic.List[uint32]]::new()
    for ($y = 0; $y -lt $bmp.Height; $y++) {
      for ($x = 0; $x -lt $bmp.Width; $x++) {
        $c = $bmp.GetPixel($x,$y)
        $a = [uint32][Math]::Round($c.A * (128.0 / 255.0))
        if ($a -eq 0) { $pixels.Add(0) }
        else { $pixels.Add([uint32]($c.R + 256*$c.G + 65536*$c.B + 16777216L*$a)) }
      }
    }
    [void]$out.AppendLine("    $name,")
    $rows.Add(@($bmp.Width,$bmp.Height,$pixels))
    $bmp.Dispose()
  }
}
[void]$out.AppendLine('    IconCount };')
[void]$out.AppendLine('constexpr IconSize kIconSizes[] = {{0, 0},')
foreach ($row in $rows) { [void]$out.AppendLine("    {$($row[0]), $($row[1])},") }
[void]$out.AppendLine('};')
[void]$out.AppendLine('constexpr PixelRun kPixelRuns[] = {')
foreach ($row in $rows) {
  $pix = $row[2]
  $line = '    '
  $i = 0
  while ($i -lt $pix.Count) {
    $j = $i + 1
    while ($j -lt $pix.Count -and $pix[$j] -eq $pix[$i]) { $j++ }
    $line += ('{{{0}, 0x{1:x8}u}},' -f ($j-$i),$pix[$i])
    if ($line.Length -gt 100) { [void]$out.AppendLine($line); $line='    ' }
    $i = $j
  }
  if ($line.Trim()) { [void]$out.AppendLine($line) }
}
[void]$out.AppendLine('};')
[IO.File]::WriteAllText((Join-Path $Source '../lcs_prompt_atlas.inc'),$out.ToString().Replace("`r`n","`n"))

