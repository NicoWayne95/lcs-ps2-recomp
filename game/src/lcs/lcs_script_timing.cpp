// [lcs] Mission scripts that count per frame, put on the game's time step - the port of the the reference port project's
// src/game/ref_script_timing.cpp (its game-internals.md 11f) to LCS.
//
// The script VM runs every script once a frame; a `WAIT 0` loop does one pass a frame. Most of LCS's scripts time
// things with TIMERA / TIMERB, GET_GAME_TIMER or the timed opcodes (0x0078 - 0x0083), but a few change a value by a
// fixed amount every pass. On the PS2 a frame is 1/30 s, so those moved at one speed; at 120 fps four times as fast.
// The survey of MAIN.SCM that found them: HANDOFF_CLAUDE_2026-11-16.md section 15, tools/lcs_scm/ (disassembler,
// searches, gen_targets.py makes the table below).
//
// LCS's interpreter (found 2026-11-16): CRunningScript::ProcessOneCommand 0x10A7A8 (a0 the script: +0x18 the IP, an
// offset from ScriptSpace = *(gp - 0x7DFC) = *(0x3CF0F4); +0x216 the NOT flag) reads the opcode and hands it to the
// range dispatchers (0x10A9A0 below 100, ...). GetPointerToScriptVariable 0x1098D8: a variable byte < 0x0C is a timer
// (local 0x5E + byte), 0x0C..0x6B a local (script + 0x60 + 4 * (byte - 0x0C + frame), frame at +0x208), 0x6C..0xCB a
// local array (+ index local, size), 0xCC..0xE5 a global (ScriptSpace + 4 * ((byte - 0xCC) << 8 | next)), from 0xE6 a
// global array (+ index local, size); an index at or past the size takes the last element.
//
// The hook on ProcessOneCommand: when the instruction at the IP is one of the listed ones - its opcode, then the
// original bytes around it (8 before, the instruction, 8 after: the copy of MAIN.SCM the game runs holds them
// unchanged, wherever a mission was loaded) - the game runs it and the change it made to its variable is scaled by
// ms_fTimeStep / (50/30) (the frame's length over the PS2's, 0..2); integers keep the fraction for the next pass. At
// 30 fps the factor is 1. LCS_SCRIPT_TIMESTEP=0: not installed; LCS_SCRIPT_TIMESTEP_LOG=1: each site's first use and
// every 10 s its runs and amounts.
